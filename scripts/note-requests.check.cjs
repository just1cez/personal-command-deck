const { test } = require('node:test')
const assert = require('node:assert/strict')
const { createNoteRequests } = require('../electron/note-requests.cjs')
test('serializes requests, deduplicates in-flight and completed requests, and retries failures', async () => {
  const sent = []
  const broker = createNoteRequests(command => sent.push(command), 50)
  const first = broker.request({ type: 'patch' }, 'first')
  const duplicate = broker.request({ type: 'patch' }, 'first')
  const second = broker.request({ type: 'patch' }, 'second')
  await new Promise(resolve => setImmediate(resolve))
  assert.equal(sent.length, 1)
  broker.acknowledge({ requestId: 'first', accepted: true, version: 1 })
  assert.deepEqual(await first, await duplicate)
  await new Promise(resolve => setImmediate(resolve))
  assert.equal(sent.length, 2)
  broker.acknowledge({ requestId: 'second', accepted: false, error: 'full', version: 1 })
  assert.equal((await second).accepted, false)
  const retry = broker.request({ type: 'patch' }, 'second')
  await new Promise(resolve => setImmediate(resolve))
  broker.acknowledge({ requestId: 'second', accepted: true, version: 2 })
  assert.equal((await retry).accepted, true)
  await broker.request({ type: 'patch' }, 'first')
  assert.equal(sent.length, 3)
})
test('times out without blocking the next request', async () => {
  const sent = []
  const broker = createNoteRequests(command => sent.push(command), 10)
  assert.equal((await broker.request({}, 'timeout')).accepted, false)
  const next = broker.request({}, 'next')
  await new Promise(resolve => setImmediate(resolve))
  broker.acknowledge({ requestId: 'next', accepted: true, version: 1 })
  assert.equal((await next).accepted, true)
})
